def clap():
    im, d = canvas()
    for s in (-1, 1):
        h = Image.new('RGBA', (S, S), T); hd = ImageDraw.Draw(h); rr(hd, (200, 150, 330, 430), 60, SK, SKO, 10)
        for k in range(4): rr(hd, (205 + k * 30, 70, 232 + k * 30, 250), 14, SK, SKO, 6)
        im.alpha_composite(h.rotate(s * 28, center=(256, 450), resample=Image.BICUBIC), (s * -20, 0))
    for a in (-35, 0, 35): r = math.radians(a); line(d, [(256 + 170 * math.sin(r), 85 - 0 * r), (256 + 215 * math.sin(r), 45)], (255, 205, 70, 255), 12)
    return im
