for (const [n, m] of Object.entries(MANIFEST)) if (!FALLBACK[n]) FALLBACK[n] = m.f || '💖';

const live = new Map(); // short name -> "<a:yuna_x:123>"
const files = () => (fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => /\.(gif|png)$/i.test(f)) : []);
const isAnimated = (name) => (MANIFEST[name] ? !!MANIFEST[name].a : fs.existsSync(path.join(DIR, `yuna_${name}.gif`)));

const e = (name) => live.get(name) || FALLBACK[name] || '💖';
const isCustom = (name) => live.has(name);
const has = (name) => live.has(name) || name in FALLBACK;
const short = (n) => String(n).replace(/^yuna_/, '');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const baseName = (f) => short(f.replace(/\.(gif|png)$/i, ''));

// Upload order: classic emojis, then everything that replaces a unicode emoji in Yuna's messages, then the rest by category.
const CAT_ORDER = ['Family', 'Hearts', 'Casino', 'Slots', 'Wine & Drinks', 'Black Market', 'Money', 'Flirty', 'Faces', 'Everyday', 'Animated', 'Pets', 'Shop', 'Ranks', 'Cards', 'Roulette'];
const priority = (name) => {
  const m = MANIFEST[name];
  if (!m) return 0;
  if (m.r && m.r.length) return 1;
  const i = CAT_ORDER.indexOf(m.c);
  return 2 + (i === -1 ? CAT_ORDER.length : i);
};

// Called once at startup: finds the bot's emojis and uploads any that are missing (in the background, resumable).
async function sync(client) {
  const out = { have: 0, uploaded: 0, failed: 0, total: 0 };
  if (!client.application || !client.application.emojis) return out;
  if (String(process.env.EMOJI_SYNC || '').toLowerCase() === 'off') { console.log('[emoji] sync is OFF (EMOJI_SYNC=off)'); return out; }
  const delay = Math.max(300, Number(process.env.EMOJI_UPLOAD_DELAY_MS) || 1100);
  try {
    const existing = await client.application.emojis.fetch();
    for (const em of existing.values()) if (em.name && em.name.startsWith('yuna_')) { live.set(short(em.name), em.toString()); out.have++; }
    const todo = files().map((f) => ({ f, name: baseName(f) })).filter((x) => !live.has(x.name)).sort((a, b) => priority(a.name) - priority(b.name) || (a.name < b.name ? -1 : 1));
    out.total = todo.length;
    if (todo.length) console.log(`[emoji] ${out.have} already uploaded, uploading ${todo.length} more in the background (about ${Math.ceil((todo.length * (delay + 300)) / 60000)} min)...`);
    let streak = 0;
    for (const { f, name } of todo) {
      try {
        const em = await client.application.emojis.create({ attachment: path.join(DIR, f), name: `yuna_${name}` });
        live.set(name, em.toString());
        out.uploaded++; streak = 0;
        if (out.uploaded % 100 === 0) console.log(`[emoji] uploaded ${out.uploaded}/${todo.length}`);
        await wait(delay);
      } catch (err) {
        out.failed++; streak++;
        console.error(`[emoji] could not upload ${name}: ${err.message}`);
        if (/maximum number|30008|emoji.*(limit|full)/i.test(err.message)) { console.error('[emoji] the bot has no emoji slots left, stopping uploads.'); break; }
        if (streak >= 15) { console.error('[emoji] too many failures in a row, stopping. It will continue next start.'); break; }
        await wait(delay * 3);
      }
    }
  } catch (err) {
    console.error('[emoji] sync failed:', err.message);
  }
  return out;
}

// Every emoji Yuna has (from the asset files), animated ones flagged, with its category.
const list = () => {
  const names = [...new Set(files().map(baseName))].sort();
  return names.map((name) => ({ name, text: e(name), animated: isAnimated(name), custom: live.has(name), cat: MANIFEST[name] ? MANIFEST[name].c : 'Classic' }));
};
const categories = () => {
  const map = new Map();
  for (const x of list()) { if (!map.has(x.cat)) map.set(x.cat, []); map.get(x.cat).push(x); }
  return [...map.entries()].sort((a, b) => (a[0] === 'Classic' ? -1 : b[0] === 'Classic' ? 1 : a[0] < b[0] ? -1 : 1));
};
const manifest = () => MANIFEST;

module.exports = { e, has, isCustom, sync, list, categories, manifest, FALLBACK, live };
