// Yuna's custom emojis. They are uploaded as APPLICATION emojis, which belong to the bot itself and work in
// every server and DM the bot is used in (animated ones included), no server permissions needed.
// Every file in assets/emojis is uploaded automatically at startup (name: yuna_<name>.png/.gif).
// Regenerate / extend the art with: python3 tools/make_assets.py  and  python3 tools/make_more_emojis.py
// If an emoji is not uploaded (yet), e('name') quietly falls back to a normal unicode emoji.
//
// Mega pack: ~1,700 extra emojis (family, hearts, casino, wine, black market, flirty, food, ...) are generated by
//   python3 tools/make_mega_emojis.py     -> assets/emojis/*  +  src/lib/emoji_manifest.json (category + fallback + unicode swaps)
// They upload in the background after startup (most useful ones first), so the bot is usable immediately.
// .env options:  EMOJI_SYNC=off  (never upload)   EMOJI_UPLOAD_DELAY_MS=1100  (pause between uploads)
